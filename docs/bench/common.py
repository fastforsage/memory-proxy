def text(n_chars, rnd):
    out = []
    while sum(len(x) + 1 for x in out) < n_chars:
        out.append(rnd.choice(S))
    return " ".join(out)[:n_chars]

def chat(messages, max_tokens=16, **kw):
    r = httpx.post(URL + "/v1/chat/completions", json={"messages": messages, "max_tokens": max_tokens,
                   "temperature": 0, "cache_prompt": True, **kw}, timeout=3600)
    r.raise_for_status()
    return r.json()

def tokens(messages):
    t = httpx.post(URL + "/apply-template", json={"messages": messages}, timeout=600).json()["prompt"]
    return httpx.post(URL + "/tokenize", json={"content": t, "add_special": False}, timeout=600).json()["tokens"]
